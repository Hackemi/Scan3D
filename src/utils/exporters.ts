import * as THREE from 'three';
import { Model3DData } from '../types';

/**
 * Downloads a text or binary file in the browser
 */
function downloadFile(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Exports a Three.js Group or Mesh to Wavefront OBJ format
 */
export function exportToOBJ(objectGroup: THREE.Group, modelName: string): void {
  let output = `# Wavefront OBJ File generated by Scan3D Studio\n`;
  output += `# Model: ${modelName}\n`;
  output += `# Date: ${new Date().toISOString()}\n\n`;

  let vertexOffset = 1;
  let normalOffset = 1;
  let uvOffset = 1;

  objectGroup.traverse((child) => {
    if ((child as THREE.Mesh).isMesh) {
      const mesh = child as THREE.Mesh;
      const geometry = mesh.geometry;
      if (!geometry) return;

      output += `o ${mesh.name || 'Component'}\n`;

      // World matrix transformation
      mesh.updateWorldMatrix(true, false);
      const matrix = mesh.matrixWorld;

      const posAttr = geometry.getAttribute('position');
      const normAttr = geometry.getAttribute('normal');
      const uvAttr = geometry.getAttribute('uv');

      if (!posAttr) return;

      const v = new THREE.Vector3();
      const n = new THREE.Vector3();

      // Vertices
      for (let i = 0; i < posAttr.count; i++) {
        v.fromBufferAttribute(posAttr, i);
        v.applyMatrix4(matrix);
        output += `v ${v.x.toFixed(4)} ${v.y.toFixed(4)} ${v.z.toFixed(4)}\n`;
      }

      // Normals
      if (normAttr) {
        const normalMatrix = new THREE.Matrix3().getNormalMatrix(matrix);
        for (let i = 0; i < normAttr.count; i++) {
          n.fromBufferAttribute(normAttr, i);
          n.applyMatrix3(normalMatrix).normalize();
          output += `vn ${n.x.toFixed(4)} ${n.y.toFixed(4)} ${n.z.toFixed(4)}\n`;
        }
      }

      // UVs
      if (uvAttr) {
        for (let i = 0; i < uvAttr.count; i++) {
          output += `vt ${uvAttr.getX(i).toFixed(4)} ${uvAttr.getY(i).toFixed(4)}\n`;
        }
      }

      // Faces (indices)
      const index = geometry.getIndex();
      if (index) {
        for (let i = 0; i < index.count; i += 3) {
          const a = index.getX(i) + vertexOffset;
          const b = index.getX(i + 1) + vertexOffset;
          const c = index.getX(i + 2) + vertexOffset;

          if (normAttr && uvAttr) {
            output += `f ${a}/${a}/${a} ${b}/${b}/${b} ${c}/${c}/${c}\n`;
          } else if (normAttr) {
            output += `f ${a}//${a} ${b}//${b} ${c}//${c}\n`;
          } else {
            output += `f ${a} ${b} ${c}\n`;
          }
        }
      } else {
        // Non-indexed
        for (let i = 0; i < posAttr.count; i += 3) {
          const a = i + vertexOffset;
          const b = i + 1 + vertexOffset;
          const c = i + 2 + vertexOffset;
          if (normAttr) {
            output += `f ${a}//${a} ${b}//${b} ${c}//${c}\n`;
          } else {
            output += `f ${a} ${b} ${c}\n`;
          }
        }
      }

      vertexOffset += posAttr.count;
      if (normAttr) normalOffset += normAttr.count;
      if (uvAttr) uvOffset += uvAttr.count;
      output += '\n';
    }
  });

  const blob = new Blob([output], { type: 'text/plain' });
  const safeName = modelName.toLowerCase().replace(/[^a-z0-9_-]/g, '_');
  downloadFile(blob, `${safeName}.obj`);
}

/**
 * Exports a Three.js Group to Stereolithography (STL) ASCII format for 3D Printing
 */
export function exportToSTL(objectGroup: THREE.Group, modelName: string): void {
  let output = `solid ${modelName || 'scan3d_model'}\n`;

  const vA = new THREE.Vector3();
  const vB = new THREE.Vector3();
  const vC = new THREE.Vector3();
  const cb = new THREE.Vector3();
  const ab = new THREE.Vector3();
  const normal = new THREE.Vector3();

  objectGroup.traverse((child) => {
    if ((child as THREE.Mesh).isMesh) {
      const mesh = child as THREE.Mesh;
      const geometry = mesh.geometry;
      if (!geometry) return;

      mesh.updateWorldMatrix(true, false);
      const matrix = mesh.matrixWorld;

      const posAttr = geometry.getAttribute('position');
      if (!posAttr) return;

      const index = geometry.getIndex();
      const faceCount = index ? index.count / 3 : posAttr.count / 3;

      for (let f = 0; f < faceCount; f++) {
        let iA = f * 3;
        let iB = f * 3 + 1;
        let iC = f * 3 + 2;

        if (index) {
          iA = index.getX(f * 3);
          iB = index.getX(f * 3 + 1);
          iC = index.getX(f * 3 + 2);
        }

        vA.fromBufferAttribute(posAttr, iA).applyMatrix4(matrix);
        vB.fromBufferAttribute(posAttr, iB).applyMatrix4(matrix);
        vC.fromBufferAttribute(posAttr, iC).applyMatrix4(matrix);

        // Compute facet normal
        cb.subVectors(vC, vB);
        ab.subVectors(vA, vB);
        cb.cross(ab).normalize();
        normal.copy(cb);

        output += `  facet normal ${normal.x.toFixed(6)} ${normal.y.toFixed(6)} ${normal.z.toFixed(6)}\n`;
        output += `    outer loop\n`;
        output += `      vertex ${vA.x.toFixed(6)} ${vA.y.toFixed(6)} ${vA.z.toFixed(6)}\n`;
        output += `      vertex ${vB.x.toFixed(6)} ${vB.y.toFixed(6)} ${vB.z.toFixed(6)}\n`;
        output += `      vertex ${vC.x.toFixed(6)} ${vC.y.toFixed(6)} ${vC.z.toFixed(6)}\n`;
        output += `    endloop\n`;
        output += `  endfacet\n`;
      }
    }
  });

  output += `endsolid ${modelName || 'scan3d_model'}\n`;

  const blob = new Blob([output], { type: 'text/plain' });
  const safeName = modelName.toLowerCase().replace(/[^a-z0-9_-]/g, '_');
  downloadFile(blob, `${safeName}.stl`);
}

/**
 * Exports point cloud to PLY format (Stanford Triangle / Point Cloud format)
 */
export function exportToPLY(
  points: Array<[number, number, number, string]>,
  modelName: string,
  objectGroup?: THREE.Group
): void {
  let pointList = points && points.length > 0 ? [...points] : [];

  // If no points provided, extract vertices directly from Three.js scene meshes
  if (pointList.length === 0 && objectGroup) {
    objectGroup.traverse((child) => {
      if ((child as THREE.Mesh).isMesh) {
        const mesh = child as THREE.Mesh;
        const geometry = mesh.geometry;
        if (!geometry) return;
        mesh.updateWorldMatrix(true, false);
        const matrix = mesh.matrixWorld;
        const posAttr = geometry.getAttribute('position');
        if (posAttr) {
          const v = new THREE.Vector3();
          const hex = (mesh.material as any)?.color?.getHexString?.()
            ? `#${(mesh.material as any).color.getHexString()}`
            : '#38bdf8';
          // Sample vertices
          for (let i = 0; i < posAttr.count; i++) {
            v.fromBufferAttribute(posAttr, i).applyMatrix4(matrix);
            pointList.push([v.x, v.y, v.z, hex]);
          }
        }
      }
    });
  }

  if (pointList.length === 0) {
    // Generate minimal fallback point cloud if still empty
    pointList = [
      [0, 0, 0, '#38bdf8'],
      [0.5, 0.5, 0.5, '#38bdf8'],
      [-0.5, -0.5, -0.5, '#38bdf8'],
    ];
  }

  let output = `ply\n`;
  output += `format ascii 1.0\n`;
  output += `comment Generated by Scan3D Studio\n`;
  output += `element vertex ${pointList.length}\n`;
  output += `property float x\n`;
  output += `property float y\n`;
  output += `property float z\n`;
  output += `property uchar red\n`;
  output += `property uchar green\n`;
  output += `property uchar blue\n`;
  output += `end_header\n`;

  pointList.forEach(([x, y, z, hex]) => {
    let r = 200, g = 200, b = 200;
    if (hex && hex.startsWith('#')) {
      const clean = hex.slice(1);
      r = parseInt(clean.substring(0, 2), 16) || 200;
      g = parseInt(clean.substring(2, 4), 16) || 200;
      b = parseInt(clean.substring(4, 6), 16) || 200;
    }
    output += `${x.toFixed(4)} ${y.toFixed(4)} ${z.toFixed(4)} ${r} ${g} ${b}\n`;
  });

  const blob = new Blob([output], { type: 'text/plain' });
  const safeName = modelName.toLowerCase().replace(/[^a-z0-9_-]/g, '_');
  downloadFile(blob, `${safeName}_pointcloud.ply`);
}

/**
 * Exports complete JSON project metadata
 */
export function exportToJSON(modelData: Model3DData): void {
  const jsonStr = JSON.stringify(modelData, null, 2);
  const blob = new Blob([jsonStr], { type: 'application/json' });
  const safeName = modelData.name.toLowerCase().replace(/[^a-z0-9_-]/g, '_');
  downloadFile(blob, `${safeName}_project.json`);
}
